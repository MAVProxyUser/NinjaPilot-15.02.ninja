/**
 * Initialise the module.  Called before the start function
 * \returns 0 on success or -1 if initialisation failed
 */
int32_t SensorsInitialize(void)
{
    // Was never seeded, so every run replayed the exact same rand()
    // sequence - including whatever unlucky draw rand_gauss() hit first.
    srand((unsigned int)PIOS_DELAY_GetRaw());

    accel_bias[0] = rand_gauss() / 10;
    accel_bias[1] = rand_gauss() / 10;
    accel_bias[2] = rand_gauss() / 10;

    AccelSensorInitialize();
    AttitudeSimulatedInitialize();
    BaroSensorInitialize();
    AirspeedSensorInitialize();
    GyroSensorInitialize();
    // GyrosBiasInitialize();
    GPSPositionSensorInitialize();
    GPSVelocitySensorInitialize();
    GPSSatellitesInitialize();
    GPSTimeInitialize();
    GPSExtendedStatusInitialize();
    FlightBatteryStateInitialize();
    /* GPSExtendedStatus is semantically the OpenPilot GPSV9 module's
     * self-description; there is no GPSV9 here, so Status stays NONE
     * (honest) and the tag names the actual receiver chain once. */
    {
        GPSExtendedStatusData ext;
        GPSExtendedStatusGet(&ext);
        ext.Status = GPSEXTENDEDSTATUS_STATUS_NONE;
        const char tag[] = "DroneCAN AP_Periph M9N";
        memset(ext.FirmwareTag, 0, sizeof(ext.FirmwareTag));
        memcpy(ext.FirmwareTag, tag, sizeof(tag) - 1);
        ext.BoardType[0] = 124; /* the DroneCAN node id serving GNSS */
        ext.BoardType[1] = 0;
        GPSExtendedStatusSet(&ext);
    }
    MagSensorInitialize();
    RevoCalibrationInitialize();

    return 0;
}

/**
 * Start the task.  Expects all objects to be initialized by this point.
 * pick \returns 0 on success or -1 if initialisation failed
 */
int32_t SensorsStart(void)
{
    // Start main task
    xTaskCreate(SensorsTask, (signed char *)"Sensors", STACK_SIZE_BYTES / 4, NULL, TASK_PRIORITY, &sensorsTaskHandle);
    PIOS_TASK_MONITOR_RegisterTask(TASKINFO_RUNNING_SENSORS, sensorsTaskHandle);
    PIOS_WDG_RegisterFlag(PIOS_WDG_SENSORS);

    return 0;
}

MODULE_INITCALL(SensorsInitialize, SensorsStart);

/**
 * Simulated sensor task.  Run a model of the airframe and produce sensor values
 */
int sensors_count;
static void SensorsTask(__attribute__((unused)) void *parameters)
{
    portTickType lastSysTime;

    AlarmsClear(SYSTEMALARMS_ALARM_SENSORS);

// HomeLocationData homeLocation;
// HomeLocationGet(&homeLocation);
// homeLocation.Latitude = 0;
// homeLocation.Longitude = 0;
// homeLocation.Altitude = 0;
// homeLocation.Be[0] = 26000;
// homeLocation.Be[1] = 400;
// homeLocation.Be[2] = 40000;
// homeLocation.Set = HOMELOCATION_SET_TRUE;
// HomeLocationSet(&homeLocation);


    // When an external physics bridge (e.g. the Gazebo bridge) is driving
    // this session, it publishes GyroSensor/AccelSensor/BaroSensor/
    // GPSPositionSensor/MagSensor itself over the same UAVTalk link this
    // module normally uses - if both write every tick they'll fight over
    // the same objects. Checked once here rather than every tick.
    bool externalPhysics = (getenv("NINJAPILOT_EXTERNAL_PHYSICS") != NULL);

    // Main task loop
    lastSysTime = xTaskGetTickCount();
    uint32_t last_time = PIOS_DELAY_GetRaw();
    while (1) {
        PIOS_WDG_UpdateFlag(PIOS_WDG_SENSORS);

#ifdef PIOS_REALPOSIX
        /*
         * REALPOSIX: publish the REAL sensors the hub thread is reading.
         *
         * The hub owns a plain pthread (see pios_sensors_hub.c) precisely so
         * this task never performs a syscall - a blocking ioctl here would
         * freeze every FreeRTOS task for the duration of the read. All this
         * does is copy a seqlock-protected snapshot and hand it to the
         * UAVObjects, which is cheap and cannot block.
         *
         * Each object is published ONLY when its counter has moved. The hub
         * samples at different rates (imu 500 Hz, baro 50, mag 25), and
         * re-publishing an unchanged value would fake sensor updates - which
         * matters because stabilizationInnerloopTask is triggered BY
         * GyroSensor updates, and the estimator gates on MagSensor arriving.
         */
        {
            static uint32_t last_imu, last_baro, last_mag, last_mag2, last_gps, last_imu2, last_baro2;
            static bool telemetry_throttled = false;

            /*
             * Throttle sensor-object TELEMETRY before the first publish.
             *
             * Locally Set() objects fire telemetry events; UAVTalk-received
             * ones do not (loop prevention). Under Gazebo the sensor objects
             * arrive via UAVTalk, so telemetry stays idle - which is why this
             * never appeared in a year of SITL. Publishing locally at 500 Hz
             * floods TelTx with ~1100 events/s; TelTx and the UDP tasks all
             * run at tskIDLE_PRIORITY+7, and once that band never goes
             * collectively idle, EVERY task at +6 and below starves - the
             * Sensors task, the estimator callbacks, IDLE included. Measured
             * on the OSD32MP1: firmware ran 2-20 s then all low-band tasks
             * froze (voluntary ctxt switches stopped dead) while the +7 band
             * cycled normally at 456-1000 wakes/s.
             *
             * Raw 500 Hz sensor streams do not belong on telemetry anyway;
             * a GCS wanting them can change the metadata explicitly.
             */
            if (!telemetry_throttled) {
                telemetry_throttled = true;
                UAVObjMetadata md;
                UAVObjHandle objs[] = {
                    GyroSensorHandle(), AccelSensorHandle(),
                    BaroSensorHandle(), MagSensorHandle(),
                    AuxMagSensorHandle()
                };
                for (unsigned i = 0; i < sizeof(objs) / sizeof(objs[0]); i++) {
                    UAVObjGetMetadata(objs[i], &md);
                    UAVObjSetTelemetryUpdateMode(&md, UPDATEMODE_PERIODIC);
                    md.telemetryUpdatePeriod = 1000;   /* 1 Hz is plenty */
                    UAVObjSetMetadata(objs[i], &md);
                }
            }
            /* static, not automatic: ~96 bytes, and only this task reads it */
            static struct pios_sensors_hub_data h;

            if (PIOS_SENSORS_HUB_Get(&h)) {
                if (h.have_imu && h.imu_count != last_imu) {
                    last_imu = h.imu_count;

                    AccelSensorData a;
                    a.x = h.accel_mss[0];
                    a.y = h.accel_mss[1];
                    a.z = h.accel_mss[2];
                    a.temperature = h.imu_temp_c;
                    AccelSensorSet(&a);

                    /* Published LAST of the pair on purpose: GyroSensor is
                     * what dispatches the inner loop, so the accel it will
                     * read is already in place when it runs. */
                    GyroSensorData g;
                    g.x = h.gyro_dps[0];
                    g.y = h.gyro_dps[1];
                    g.z = h.gyro_dps[2];
                    g.temperature = h.imu_temp_c;
                    GyroSensorSet(&g);
                }

                /*
                 * IMU failover: the second MPU-9150 rides the CAN bus via
                 * the L431's compact stream. It is NOT fused with the local
                 * sensor - same part, no shared clock - it takes over
                 * publishing only when the local I2C stream has been silent
                 * for 200 ms (100 lost samples at 500 Hz), and stands down
                 * the moment the local sensor speaks again. The inner loop
                 * then keeps closing at the CAN rate instead of dying with
                 * the I2C bus. Timestamps are both hub CLOCK_MONOTONIC, so
                 * the comparison needs no clock read here.
                 */
                if (h.have_imu2 && h.imu2_count != last_imu2) {
                    last_imu2 = h.imu2_count;
                    static bool failed_over = false;
                    bool local_dead = !h.have_imu
                                      || (h.imu2_time - h.imu_time) > 0.2;
                    if (local_dead) {
                        if (!failed_over) {
                            failed_over = true;
                            PIOS_SHMLOG_Printf("[sensors] LOCAL IMU SILENT - failing over to CAN IMU stream");
                        }
                        AccelSensorData a2;
                        a2.x = h.imu2_accel_mss[0];
                        a2.y = h.imu2_accel_mss[1];
                        a2.z = h.imu2_accel_mss[2];
                        a2.temperature = h.imu_temp_c;
                        AccelSensorSet(&a2);

                        GyroSensorData g2;
                        g2.x = h.imu2_gyro_dps[0];
                        g2.y = h.imu2_gyro_dps[1];
                        g2.z = h.imu2_gyro_dps[2];
                        g2.temperature = h.imu_temp_c;
                        GyroSensorSet(&g2);
                    } else if (failed_over) {
                        failed_over = false;
                        PIOS_SHMLOG_Printf("[sensors] local IMU back - CAN IMU stands down");
                    }
                }

                /*
                 * Baro failover, same policy as the IMU pair: the local
                 * BMP280 publishes BaroSensor ONLY while the CAN baro has
                 * been silent >1 s, and stands down when it returns. The
                 * two units carry a ~131 Pa absolute offset (~11 m), so a
                 * source switch steps the altitude - failover is for a
                 * DEAD bus, never for blending.
                 */
                if (h.have_baro2 && h.baro2_count != last_baro2) {
                    last_baro2 = h.baro2_count;
                    static bool baro_failed_over = false;
                    bool can_baro_dead = !h.have_baro
                                         || (h.baro2_time - h.baro_time) > 1.0;
                    if (can_baro_dead) {
                        if (!baro_failed_over) {
                            baro_failed_over = true;
                            PIOS_SHMLOG_Printf("[sensors] CAN BARO SILENT - failing over to local BMP280");
                        }
                        BaroSensorData b2;
                        b2.Temperature = h.baro2_temp_c;
                        b2.Pressure    = h.baro2_press_pa / 1000.0f;
                        b2.Altitude    = 44330.0f * (1.0f - powf(b2.Pressure / 101.325f, 0.190295f));
                        BaroSensorSet(&b2);
                    } else if (baro_failed_over) {
                        baro_failed_over = false;
                        PIOS_SHMLOG_Printf("[sensors] CAN baro back - local BMP280 stands down");
                    }
                }

                if (h.have_baro && h.baro_count != last_baro) {
                    last_baro = h.baro_count;

                    BaroSensorData b;
                    b.Temperature = h.baro_temp_c;
                    b.Pressure    = h.press_pa / 1000.0f;   /* Pa -> kPa */
                    /* International Standard Atmosphere, the same relation
                     * pios_ms5611.c uses. 101.325 kPa / 288.15 K sea level. */
                    b.Altitude    = 44330.0f *
                                    (1.0f - powf(b.Pressure / 101.325f,
                                                 (1.0f / 5.255f)));
                    BaroSensorSet(&b);
                }

                if (h.have_mag2 && h.mag2_count != last_mag2) {
                    last_mag2 = h.mag2_count;

                    /*
                     * The HMC5883L goes to AuxMagSensor, not MagSensor: this
                     * tree already has auxmagsupport.c to fuse a second
                     * magnetometer, and MagSensor belongs to the RM3100 -
                     * which is the better part by ~25x on quantisation
                     * (12.2 nT vs ~300 nT) and is the one the estimator
                     * should trust. Two sensors writing one object would
                     * just be the last writer winning.
                     *
                     * Status is GOOD unconditionally because the driver
                     * already rejects the -4096 saturation flag at the
                     * source - a reading that reaches here is real.
                     */
                    AuxMagSensorData am;
                    am.x = h.mag2_ga[0] * 1000.0f;          /* Ga -> mGa */
                    am.y = h.mag2_ga[1] * 1000.0f;
                    am.z = h.mag2_ga[2] * 1000.0f;
                    am.Status = AUXMAGSENSOR_STATUS_OK;
                    AuxMagSensorSet(&am);
                }

                if (h.gps_count != last_gps) {
                    last_gps = h.gps_count;

                    /* Truthful no-fix publishing: Status carries the fix
                     * state, so filterlla's gates ignore the zeros rather
                     * than fusing them. Fix2 carries only PDOP; HDOP/VDOP
                     * are set to it rather than invented. */
                    GPSPositionSensorData gp;
                    GPSPositionSensorGet(&gp);
                    gp.Latitude   = h.gps_lat_1e7;
                    gp.Longitude  = h.gps_lon_1e7;
                    gp.Altitude   = h.gps_alt_msl_m;
                    gp.Satellites = (int8_t)h.gps_sats;
                    gp.PDOP       = h.gps_pdop;
                    /* real HDOP/VDOP from gnss.Auxiliary when it has
                     * arrived; PDOP stands in only until then */
                    gp.HDOP       = (h.gps_aux_count > 0) ? h.gps_hdop : h.gps_pdop;
                    gp.VDOP       = (h.gps_aux_count > 0) ? h.gps_vdop : h.gps_pdop;
                    gp.SensorType = GPSPOSITIONSENSOR_SENSORTYPE_DRONECAN;
                    gp.Status     = (h.gps_fix == 3) ? GPSPOSITIONSENSOR_STATUS_FIX3D :
                                    (h.gps_fix == 2) ? GPSPOSITIONSENSOR_STATUS_FIX2D :
                                    GPSPOSITIONSENSOR_STATUS_NOFIX;
                    if (h.gps_fix >= 2) {
                        gp.Groundspeed = sqrtf(h.gps_ned_vel[0] * h.gps_ned_vel[0]
                                               + h.gps_ned_vel[1] * h.gps_ned_vel[1]);
                        gp.Heading = atan2f(h.gps_ned_vel[1], h.gps_ned_vel[0])
                                     * 57.29578f;
                        if (gp.Heading < 0.0f) {
                            gp.Heading += 360.0f;
                        }
                    } else {
                        gp.Groundspeed = 0.0f;
                        gp.Heading     = 0.0f;
                    }
                    GPSPositionSensorSet(&gp);

                    if (h.gps_fix == 3) {
                        GPSVelocitySensorData gv;
                        gv.North = h.gps_ned_vel[0];
                        gv.East  = h.gps_ned_vel[1];
                        gv.Down  = h.gps_ned_vel[2];
                        GPSVelocitySensorSet(&gv);
                    }

                    /* 1 Hz enrichment - everything the DroneCAN suite
                     * actually carries, published truthfully:
                     *  - GPSSatellites.SatsInView from gnss.Auxiliary's
                     *    sats_visible (per-satellite PRN/El/Az/SNR do not
                     *    exist on this bus - zeroed, not invented)
                     *  - GPSTime from Fix2's UTC timestamp (present once
                     *    the receiver has time from the sky, before a
                     *    position fix) */
                    static uint32_t last_gps_enrich_ms = 0;
                    uint32_t now_ms = xTaskGetTickCount() * portTICK_RATE_MS;
                    if ((now_ms - last_gps_enrich_ms) >= 1000) {
                        last_gps_enrich_ms = now_ms;

                        if (h.gps_aux_count > 0) {
                            GPSSatellitesData sat;
                            memset(&sat, 0, sizeof(sat));
                            sat.SatsInView = (int8_t)h.gps_sats_visible;
                            GPSSatellitesSet(&sat);
                        }

                        if (h.gps_utc_usec != 0) {
                            time_t utc_s = (time_t)(h.gps_utc_usec / 1000000ull);
                            struct tm tm_utc;
                            if (gmtime_r(&utc_s, &tm_utc) != NULL) {
                                GPSTimeData gt;
                                gt.Year   = (int16_t)(tm_utc.tm_year + 1900);
                                gt.Month  = (int8_t)(tm_utc.tm_mon + 1);
                                gt.Day    = (int8_t)tm_utc.tm_mday;
                                gt.Hour   = (int8_t)tm_utc.tm_hour;
                                gt.Minute = (int8_t)tm_utc.tm_min;
                                gt.Second = (int8_t)tm_utc.tm_sec;
                                GPSTimeSet(&gt);
                            }
                        }
                    }
                }

                if (h.have_mag && h.mag_count != last_mag) {
                    last_mag = h.mag_count;

                    MagSensorData m;
                    m.x = h.mag_ga[0] * 1000.0f;            /* Ga -> mGa */
                    m.y = h.mag_ga[1] * 1000.0f;
                    m.z = h.mag_ga[2] * 1000.0f;
                    m.temperature = h.baro_temp_c;
                    MagSensorSet(&m);
                }

                /* Second compass, the QMC5883P riding the M9N GPS module
                 * (node 124), published as the AUX mag: visible in the GCS
                 * and available to filtermag per AuxMagSettings.Usage.
                 * UNCALIBRATED - bench |B| reads ~76 uT vs the RM3100's
                 * ~51 - so default Usage should keep the RM3100 primary. */
                static uint32_t last_qmc = 0;
                if (h.qmc_count != last_qmc) {
                    last_qmc = h.qmc_count;

                    AuxMagSensorData am;
                    am.x = h.qmc_ga[0] * 1000.0f;           /* Ga -> mGa */
                    am.y = h.qmc_ga[1] * 1000.0f;
                    am.z = h.qmc_ga[2] * 1000.0f;
                    am.Status = AUXMAGSENSOR_STATUS_OK;
                    AuxMagSensorSet(&am);
                }

                /*
                 * Transport health tiles, once per second. These report the
                 * SENSOR TRANSPORT, not the fusion chain: the tiles read as
                 * hardware health, and Basic(Complementary) fusion would
                 * otherwise leave MAG greyed forever. Both alarms stay
                 * Uninitialised (greyed) until the hardware is first seen,
                 * which keeps "never detected" distinguishable from "died".
                 */
                {
                    static uint32_t health_div = 0;
                    if (++health_div >= 500) {   /* 500 x 2 ms = 1 s */
                        health_div = 0;

                        /* MAG: RM3100 over CAN, native 25 Hz. Only owned
                         * here under Basic(Complementary); the mag fusion
                         * chains hand this alarm to filtermag's deviation
                         * check, which judges the DATA, not just delivery. */
                        RevoSettingsData revo;
                        RevoSettingsGet(&revo);
                        if (revo.FusionAlgorithm == REVOSETTINGS_FUSIONALGORITHM_BASICCOMPLEMENTARY) {
                            static uint32_t prev_mag_count = 0;
                            static uint8_t mag_quiet_s = 0;
                            if (h.mag_count > 0) {
                                if (h.mag_count != prev_mag_count) {
                                    uint32_t delta = h.mag_count - prev_mag_count;
                                    prev_mag_count = h.mag_count;
                                    mag_quiet_s    = 0;
                                    if (delta >= 13) {   /* at least half the native rate */
                                        AlarmsClear(SYSTEMALARMS_ALARM_MAGNETOMETER);
                                    } else {
                                        AlarmsSet(SYSTEMALARMS_ALARM_MAGNETOMETER, SYSTEMALARMS_ALARM_WARNING);
                                    }
                                } else {
                                    if (mag_quiet_s < 255) {
                                        mag_quiet_s++;
                                    }
                                    AlarmsSet(SYSTEMALARMS_ALARM_MAGNETOMETER,
                                              mag_quiet_s >= 3 ? SYSTEMALARMS_ALARM_ERROR
                                              : SYSTEMALARMS_ALARM_WARNING);
                                }
                            }
                        }

                        /* CAN0 bus load on the former I2C tile: green under
                         * half the 1 Mbit wire, orange to 80 %, red above -
                         * and red too if the bus dies after first contact. */
                        /* PWR/BATT tile: green on the jack, orange on USB
                         * VBUS (bench power - it cannot fly motors). Greyed
                         * until the OTG registers are first readable. */
                        if (h.have_pwr) {
                            if (h.vbus_present) {
                                AlarmsSet(SYSTEMALARMS_ALARM_BATTERY, SYSTEMALARMS_ALARM_WARNING);
                                /* tethered USB power = effectively unlimited
                                 * runtime, so the flight-time tile reads green
                                 * (no Battery module runs on this bench to
                                 * contest the alarm) */
                                AlarmsClear(SYSTEMALARMS_ALARM_FLIGHTTIME);

                                /* PFD battery slide-out on USB power:
                                 * nominal VBUS 5.00 V (the OTG block gives
                                 * presence only - there is no VBUS ADC or
                                 * current-sense path on this board, so
                                 * Current stays 0.00 until real hardware
                                 * exists); EstimatedFlightTime = 999999 is
                                 * the TETHERED SENTINEL the QML renders as
                                 * a green infinity for time-left and mAh. */
                                FlightBatteryStateData batt;
                                FlightBatteryStateGet(&batt);
                                batt.Voltage = 5.00f;
                                batt.Current = 0.00f;
                                batt.ConsumedEnergy = 0.0f;
                                batt.EstimatedFlightTime = 999999.0f;
                                FlightBatteryStateSet(&batt);
                            } else {
                                AlarmsClear(SYSTEMALARMS_ALARM_BATTERY);
                            }
                        }

                        static uint32_t prev_can_frames = 0;
                        if (h.can_seen) {
                            bool quiet = (h.can_frames == prev_can_frames);
                            prev_can_frames = h.can_frames;
                            if (quiet) {
                                AlarmsSet(SYSTEMALARMS_ALARM_I2C, SYSTEMALARMS_ALARM_CRITICAL);
                            } else if (h.can_load_pm > 800) {
                                AlarmsSet(SYSTEMALARMS_ALARM_I2C, SYSTEMALARMS_ALARM_ERROR);
                            } else if (h.can_load_pm > 500) {
                                AlarmsSet(SYSTEMALARMS_ALARM_I2C, SYSTEMALARMS_ALARM_WARNING);
                            } else {
                                AlarmsClear(SYSTEMALARMS_ALARM_I2C);
                            }
                        }
                    }
                }
            }
            vTaskDelay(2 / portTICK_RATE_MS);
            continue;
        }
#endif /* PIOS_REALPOSIX */

        if (externalPhysics) {
            vTaskDelay(2 / portTICK_RATE_MS);
            continue;
        }

        SystemSettingsData systemSettings;
        SystemSettingsGet(&systemSettings);

        switch (systemSettings.AirframeType) {
        case SYSTEMSETTINGS_AIRFRAMETYPE_FIXEDWING:
        case SYSTEMSETTINGS_AIRFRAMETYPE_FIXEDWINGELEVON:
        case SYSTEMSETTINGS_AIRFRAMETYPE_FIXEDWINGVTAIL:
            sensor_sim_type = MODEL_AIRPLANE;
            break;
        case SYSTEMSETTINGS_AIRFRAMETYPE_QUADX:
        case SYSTEMSETTINGS_AIRFRAMETYPE_QUADP:
        case SYSTEMSETTINGS_AIRFRAMETYPE_VTOL:
        case SYSTEMSETTINGS_AIRFRAMETYPE_HEXA:
        case SYSTEMSETTINGS_AIRFRAMETYPE_OCTO:
            sensor_sim_type = MODEL_QUADCOPTER;
            break;
        default:
            sensor_sim_type = MODEL_AGNOSTIC;
        }

        static int i;
        i++;
        if (i % 5000 == 0) {
            // float dT = PIOS_DELAY_DiffuS(last_time) / 10.0e6;
            // fprintf(stderr, "Sensor relative timing: %f\n", dT);
            last_time = PIOS_DELAY_GetRaw();
        }

        sensors_count++;

        switch (sensor_sim_type) {
        case CONSTANT:
            simulateConstant();
            break;
        case MODEL_AGNOSTIC:
            simulateModelAgnostic();
            break;
        case MODEL_QUADCOPTER:
            simulateModelQuadcopter();
            break;
        case MODEL_AIRPLANE:
            simulateModelAirplane();
        }

        vTaskDelay(2 / portTICK_RATE_MS);
    }
}

